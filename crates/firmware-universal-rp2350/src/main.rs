#[embassy_executor::main(
    executor = "board_generic_rp2350::embassy_rp::executor::Executor",
    entry = "cortex_m_rt::entry"
)]
async fn main(_spawner: Spawner) {
    let p = embassy_rp::init(Default::default());
    let mut device = DeviceManager::<FLASH_SIZE>::new(p, &BOARD_PROFILE, MCU_FAMILY);

    let caps = device.board.capabilities();
    let identity = device.identity();
    let mcu = device.mcu_identity();
    info!(
        "AegisToken {} boot: gpio={} fido_hid={} management_hid={}",
        aegis_core::VERSION,
        caps.gpio_count,
        caps.usb.fido_hid,
        caps.usb.management_hid,
    );
    info!(
        "board identity: {} {} rev{}",
        identity.manufacturer, identity.board, identity.revision
    );
    info!(
        "mcu identity: revision={} unique_id={=u64:x}",
        mcu.revision, mcu.unique_id
    );
    // The device root key seals applet state at rest. Without a provisioned
    // key the applets run on volatile stores, exactly as before.
    let root_key = board_generic_rp2350::otp::read_root_key().ok();
    info!("device root key provisioned: {}", root_key.is_some());
    if VENDOR_KEY_IS_DEV {
        info!("warning: development firmware-update vendor key in use");
    }
    let bootsel_held = read_bootsel_stable(&mut device.board).await;
    let destination = aegis_core::state::boot_destination(bootsel_held);
    let plan = BootPlan::for_destination(destination);
    if aegis_core::ExecutionState::Boot
        .transition(destination)
        .is_err()
    {
        error!("illegal boot destination transition");
    }
    info!(
        "boot destination {} (bootsel held: {}) plan: fido={} ccid={} management={} otp_lab={} sealed_credentials={} sealed_applets={}",
        destination_label(destination),
        bootsel_held,
        plan.fido(),
        plan.ccid(),
        plan.management(),
        plan.otp_lab(),
        plan.sealed_credential_store(),
        plan.sealed_applet_stores(),
    );
    // Load the persisted configuration, falling back to factory defaults when
    // none exists or it no longer matches this device.
    let initial_config = load_config(&mut device.board, &caps, identity);
    let mut management =
        ManagementService::new(caps, identity, initial_config, LifecycleState::Factory);
    // The diagnostics report shows the boot plan, so a device muted by the
    // plan can be told apart from a broken one.
    management.set_boot_plan(plan);

    // Apply the persisted LED configuration so the status LED reflects the
    // stored behavior from the moment the device boots.
    let mut boot_led = device.board.led();
    apply_led_config(&mut boot_led, management.config());

    device.board.start_watchdog(WATCHDOG_TIMEOUT);

    selftest::run(&mut device.board, device.rng.get_mut(), identity);

    let Usb {
        device: usb_device,
        fido,
        management: management_hid,
        otp,
        ccid,
    } = device.usb;
    let (fido_reader, fido_writer) = fido.split();
    let (management_reader, management_writer) = management_hid.split();

    // Split the board so the FIDO task can await the profile-selected User
    // Presence source while housekeeping owns the LED, storage and watchdog.
    let BoardParts {
        presence,
        led,
        storage,
        watchdog,
    } = device.board.split();

    join3(
        usb_supervisor(usb_device),
        async {
            if plan.fido() {
                fido_task(
                    fido_reader,
                    fido_writer,
                    &device.rng,
                    presence,
                    storage,
                    root_key,
                    plan,
                )
                .await;
            } else {
                info!("FIDO path denied by the boot plan");
                core::future::pending::<()>().await;
            }
        },
        join3(
            housekeeping(
                management_reader,
                management_writer,
                &mut management,
                storage,
                led.map(|led| led as &mut dyn Led),
                watchdog,
            ),
            async {
                if plan.ccid() {
                    ccid_task(ccid, &device.rng, presence, storage, root_key, plan).await;
                } else {
                    info!("CCID path denied by the boot plan");
                    core::future::pending::<()>().await;
                }
            },
            async {
                if plan.otp_lab() {
                    otp_task(otp).await;
                } else {
                    info!("laboratory OTP HID denied by the boot plan");
                    core::future::pending::<()>().await;
                }
            },
        ),
    )
    .await;
}

/// Number of BOOTSEL samples read at boot.
const BOOTSEL_SAMPLES: u32 = 3;

/// Read the BOOTSEL button at boot, requiring a stable level.
///
/// The button decides the boot destination, and a destination of `Recovery`
/// mutes the FIDO and CCID paths: a single glitch on the pad would leave a
/// device that enumerates but never answers. The pad is therefore sampled a
/// few times; an unstable reading is treated as "not pressed" and logged.
async fn read_bootsel_stable<const FLASH_SIZE: usize>(board: &mut Board<FLASH_SIZE>) -> bool {
    let pressed = board.bootsel_pressed();
    let mut stable = true;
    for _ in 1..BOOTSEL_SAMPLES {
        Timer::after_millis(1).await;
        let sample = board.bootsel_pressed();
        if sample != pressed {
            stable = false;
        }
    }
    if !stable {
        warn!("BOOTSEL reading unstable at boot; treating it as released");
        return false;
    }
    pressed
}

/// Short label of a boot destination, for the boot log.
fn destination_label(destination: aegis_core::ExecutionState) -> &'static str {
    match destination {
        aegis_core::ExecutionState::Active => "active",
        aegis_core::ExecutionState::Recovery => "recovery",
        aegis_core::ExecutionState::Locked => "locked",
        _ => "other",
    }
}

/// Drive only the 1050:0407 experimental OTP-labelled HID endpoint. Every
/// accepted request is bounded and read-only; malformed/partial reports are
/// ignored. No flash, FIDO, CCID, presence, or Management resource is locked.
async fn otp_task(otp: Option<OtpHid>) {
    let Some(otp) = otp else {
        // Generic and third-party identities do not enumerate this interface.
        core::future::pending::<()>().await;
        return;
    };
    let (mut reader, mut writer) = otp.split();
    let mut report = [0u8; otp_lab::REPORT_SIZE];
    loop {
        let Ok(len) = reader.read(&mut report).await else {
            reader.ready().await;
            continue;
        };
        if let Some(response) = otp_lab::handle_report(&report[..len]) {
            if writer.write(&response).await.is_err() {
                writer.ready().await;
            }
        }
    }
}

/// Serve the CCID interface: reassemble host messages and answer with the
/// applet router.
///
/// PIV, OATH and the P-256 OpenPGP slice are live applets. Applet state is
/// sealed to flash when the device root key is provisioned, and falls back to
/// volatile stores otherwise.
///
/// The boot plan gates the path: a denied plan neither serves CCID nor opens
/// the sealed applet stores.
async fn ccid_task<const FLASH_SIZE: usize>(
    mut ccid: Ccid,
    rng: &Mutex<CriticalSectionRawMutex, HardwareRng>,
    presence: &Mutex<CriticalSectionRawMutex, PresenceAdapter>,
    storage: &CriticalSectionMutex<RefCell<FlashStorage<FLASH_SIZE>>>,
    root_key: Option<[u8; aegis_core::secret::KEY_LEN]>,
    plan: BootPlan,
) {
    if !plan.ccid() {
        info!("CCID path denied by the boot plan");
        core::future::pending::<()>().await;
        return;
    }

    let layout = BOARD_PROFILE.hardware.flash.layout;
    let region = RegionStorage::new(storage, layout.applet_offset);
    let base = |store: u32| layout.applet_store_offset(store);

    if !plan.sealed_applet_stores() {
        info!("applet stores not authorized by the boot plan");
        core::future::pending::<()>().await;
        return;
    }

    if let Some(key) = root_key {
        let piv_layout = PivLayout {
            meta: base(aegis_applets::sealed::PIV_META_STORE),
            objects: core::array::from_fn(|i| {
                base(aegis_applets::sealed::PIV_OBJECT_STORE_BASE + i as u32)
            }),
        };
        let oath_data: [u32; OATH_SHARDS] =
            core::array::from_fn(|i| base(OATH_DATA_STORE_BASE + i as u32));
        let pgp_data: [u32; OPENPGP_SHARDS] =
            core::array::from_fn(|i| base(OPENPGP_DATA_STORE_BASE + i as u32));
        let piv = SealedPivStore::open(region, &piv_layout, SLOT_SIZE, &key);
        let oath =
            SealedOathStore::open(region, oath_data, base(OATH_COMMIT_STORE), SLOT_SIZE, &key);
        let openpgp = SealedOpenPgpStore::open(
            region,
            pgp_data,
            base(OPENPGP_COMMIT_STORE),
            SLOT_SIZE,
            &key,
        );
        match (piv, oath, openpgp) {
            (Ok(piv), Ok(oath), Ok(openpgp)) => {
                info!("applet stores sealed to flash");
                let mut piv = Piv::new(piv);
                let mut openpgp = OpenPgp::new(openpgp);
                let mut oath = Oath::new(oath);
                run_card(&mut ccid, rng, presence, &mut piv, &mut openpgp, &mut oath).await;
                return;
            }
            (piv, oath, openpgp) => {
                if piv.is_err() {
                    info!("PIV sealed store unavailable; using memory");
                }
                if oath.is_err() {
                    info!("OATH sealed store unavailable; using memory");
                }
                if openpgp.is_err() {
                    info!("OpenPGP sealed store unavailable; using memory");
                }
            }
        }
    } else {
        info!("no root key; applet state will not persist");
    }

    let mut piv = Piv::new(MemoryPivStore::new());
    let mut openpgp = OpenPgp::new(MemoryOpenPgpStore::new());
    let mut oath = Oath::new(MemoryOathStore::new());
    run_card(&mut ccid, rng, presence, &mut piv, &mut openpgp, &mut oath).await;
}

/// Drive one CCID card session: reassemble host messages and answer with the
/// applet router, sharing RNG and presence with the FIDO task.
async fn run_card<P, G, O>(
    ccid: &mut Ccid,
    rng: &Mutex<CriticalSectionRawMutex, HardwareRng>,
    presence: &Mutex<CriticalSectionRawMutex, PresenceAdapter>,
    piv: &mut P,
    openpgp: &mut G,
    oath: &mut O,
) where
    P: Applet,
    G: Applet,
    O: Applet,
{
    let mut applets: [&mut dyn Applet; 3] = [piv, openpgp, oath];
    let mut card: aegis_applets::card::DefaultCard<'_> = Card::new(&mut applets);
    let mut in_buf = [0u8; board_generic_rp2350::ccid::MAX_PACKET_SIZE as usize];
    let mut out_buf = [0u8; aegis_applets::ccid::MAX_MESSAGE_BYTES];

    loop {
        let Ok(len) = ccid.read(&mut in_buf).await else {
            continue;
        };
        if card.feed(&in_buf[..len]).is_err() {
            card.reset();
            continue;
        }
        loop {
            let outcome = {
                let mut rng = rng.lock().await;
                card.poll(&mut *rng, &mut out_buf)
            };
            match outcome {
                Ok(Some(Outcome::Response(len))) => {
                    if ccid.write(&out_buf[..len]).await.is_err() {
                        break;
                    }
                }
                Ok(Some(Outcome::PresenceRequired)) => {
                    // PIV touch policy: wait for the same physical presence
                    // source the FIDO task uses, then finish the signature
                    // with fresh RNG (RSA blinding re-randomizes per op).
                    let confirmed = wait_presence(presence).await;
                    let outcome = {
                        let mut rng = rng.lock().await;
                        card.complete_presence(confirmed, &mut *rng, &mut out_buf)
                    };
                    let Ok(Some(len)) = outcome else {
                        continue;
                    };
                    if ccid.write(&out_buf[..len]).await.is_err() {
                        break;
                    }
                }
                Ok(None) => break,
                Err(_) => {
                    card.reset();
                    break;
                }
            }
        }
    }
}

/// Wait for User Presence on the shared source.
async fn wait_presence(presence: &Mutex<CriticalSectionRawMutex, PresenceAdapter>) -> bool {
    let mut guard = presence.lock().await;
    guard.wait().await.is_ok()
}

/// Interval between CTAPHID keepalive notifications, in milliseconds.
const KEEPALIVE_INTERVAL_MS: u64 = 100;

/// Wait for User Presence, notifying the host meanwhile.
///
/// A host waiting for the user needs periodic traffic on the FIDO channel or
/// it may time the request out; a keepalive frame keeps the channel alive
/// while the presence window is open. The presence state machine keeps its
/// debounce window across the notifications.
async fn wait_presence_notifying(
    chan: &mut FidoChannel<'_>,
    status: u8,
    presence: &Mutex<CriticalSectionRawMutex, PresenceAdapter>,
) -> bool {
    let mut guard = presence.lock().await;
    let mut elapsed = 0u64;
    loop {
        match guard.poll_presence() {
            Ok(true) => return true,
            Ok(false) => {}
            Err(_) => return false,
        }
        Timer::after_millis(1).await;
        elapsed += 1;
        if elapsed % KEEPALIVE_INTERVAL_MS == 0 {
            let report = ctaphid::keepalive_report(chan.channel, status);
            chan.write(&report).await;
        }
    }
}

/// Drive the USB device and honor soft-detach requests from the Management
/// channel.
///
/// `UsbDevice::run()` holds a mutable borrow of the device, so the Management
/// task cannot disable it directly. Instead the `SoftDetach` command signals
/// [`DETACH`]; when it fires we stop driving the device and disable the
/// peripheral, which the host observes as a clean removal.
async fn usb_supervisor(mut device: UsbDevice<'static, RpUsb>) -> ! {
    loop {
        match select(device.run(), DETACH.wait()).await {
            // `run()` never resolves; only the detach signal can win.
            Either::First(never) => match never {},
            Either::Second(()) => {
                device.disable().await;
                // Stay detached until the host re-enumerates (replug/power cycle).
                core::future::pending().await
            }
        }
    }
}

/// Load and validate the persisted configuration, or return the defaults.
fn load_config<const FLASH_SIZE: usize>(
    board: &mut Board<FLASH_SIZE>,
    capabilities: &aegis_core::DeviceCapabilities,
    identity: BoardIdentity,
) -> DeviceConfig {
    let mut store = ConfigStorage::new(board.storage(), CONFIG_BASE, SLOT_SIZE);
    match store.load() {
        Ok(Some(config)) => {
            let context = ValidationContext {
                capabilities,
                lifecycle: LifecycleState::Factory,
                identity,
            };
            if config.validate(&context).is_ok() {
                info!("configuration loaded from flash");
                return config;
            }
            info!("stored configuration invalid; using defaults");
        }
        Ok(None) => info!("no stored configuration; using defaults"),
        Err(_) => info!("configuration read failed; using defaults"),
    }
    DeviceConfig::for_board(identity, capabilities)
}

/// Persist the active configuration.
fn persist_config(storage: &mut dyn Storage, config: &DeviceConfig) {
    let mut store = ConfigStorage::new(storage, CONFIG_BASE, SLOT_SIZE);
    match store.commit(config) {
        Ok(sequence) => info!("configuration persisted (sequence {})", sequence),
        Err(_) => info!("configuration persistence failed"),
    }
}

/// Apply the LED section of a configuration to the board hardware, if present.
fn apply_led_config(led: &mut Option<&mut dyn Led>, config: &DeviceConfig) {
    if let Some(led) = led.as_mut() {
        if (*led).configure(&config.led).is_err() {
            info!("LED configuration rejected by hardware");
        }
    }
}

/// Serve the CTAPHID transport and CTAP2 commands.
///
/// Credentials and PIN state are sealed to flash when the device root key is
/// provisioned; otherwise they live in a volatile store as before.
///
/// The boot plan gates the path: a denied plan neither serves FIDO nor opens
/// the sealed credential store.
async fn fido_task<const FLASH_SIZE: usize>(
    reader: FidoReader,
    writer: FidoWriter,
    rng: &Mutex<CriticalSectionRawMutex, HardwareRng>,
    presence: &Mutex<CriticalSectionRawMutex, PresenceAdapter>,
    storage: &CriticalSectionMutex<RefCell<FlashStorage<FLASH_SIZE>>>,
    root_key: Option<[u8; aegis_core::secret::KEY_LEN]>,
    plan: BootPlan,
) {
    if !plan.fido() {
        info!("FIDO path denied by the boot plan");
        core::future::pending::<()>().await;
        return;
    }

    if !plan.sealed_credential_store() {
        info!("FIDO credential store not authorized by the boot plan");
        core::future::pending::<()>().await;
        return;
    }

    if let Some(key) = root_key {
        let layout = BOARD_PROFILE.hardware.flash.layout;
        let region = RegionStorage::new(storage, layout.applet_offset);
        let base = layout.applet_store_offset(FIDO_CRED_STORE);
        match SealedCredentialStore::open(region, base, SLOT_SIZE, &key) {
            Ok(mut store) => {
                info!("FIDO credential store sealed to flash");
                run_fido(reader, writer, rng, presence, &mut store).await;
            }
            Err(_) => info!("FIDO sealed credential store unavailable; using memory"),
        }
    } else {
        info!("no root key; FIDO credentials will not persist");
    }

    let mut store = MemoryCredentialStore::new();
    run_fido(reader, writer, rng, presence, &mut store).await;
}

/// The FIDO channel a request arrived on, with the writer used to answer it.
///
/// Keepalive notifications go out on the same channel as the request they
/// refer to, so the host can match them to the pending operation.
struct FidoChannel<'a> {
    writer: &'a mut FidoWriter,
    channel: u32,
}

impl FidoChannel<'_> {
    /// Write a raw report to the FIDO endpoint.
    async fn write(&mut self, report: &[u8]) {
        let _ = self.writer.write(report).await;
    }

    /// Send a CTAPHID message on this channel.
    async fn send(&mut self, command: CtapHidCommand, payload: &[u8]) {
        send_ctaphid(self.writer, self.channel, command, payload).await;
    }
}

/// Cursor for the stateful credential-management enumeration commands.
///
/// The CTAP2.1 enumeration subcommands are split in a `Begin` command and a
/// `GetNext` command; the authenticator keeps the position between them.
#[derive(Default)]
struct EnumerationState {
    /// Relying parties returned by the last `enumerateRPsBegin`.
    rps: heapless::Vec<
        aegis_core::authenticator::RpEntry,
        { aegis_core::authenticator::MAX_CREDENTIALS },
    >,
    /// Index of the next relying party to return.
    rp_index: usize,
    /// Credential ids returned by the last `enumerateCredentialsBegin`.
    credentials:
        heapless::Vec<heapless::Vec<u8, 32>, { aegis_core::authenticator::MAX_CREDENTIALS }>,
    /// Index of the next credential to return.
    credential_index: usize,
}

/// State shared by the CTAP2 commands of one FIDO session.
struct FidoSession {
    /// PIN/UV auth handler.
    client_pin: ClientPin,
    /// Credential-management enumeration cursor.
    enumeration: EnumerationState,
    /// Pending assertion, for `authenticatorGetNextAssertion`.
    assertion: Option<aegis_core::assertion::PendingAssertion>,
}

impl FidoSession {
    /// Create a session with no PIN/UV auth token.
    fn new() -> Self {
        Self {
            client_pin: ClientPin::new(),
            enumeration: EnumerationState::default(),
            assertion: None,
        }
    }
}

/// Drive the FIDO interface with a credential store.
async fn run_fido<S>(
    mut reader: FidoReader,
    mut writer: FidoWriter,
    rng: &Mutex<CriticalSectionRawMutex, HardwareRng>,
    presence: &Mutex<CriticalSectionRawMutex, PresenceAdapter>,
    store: &mut S,
) -> !
where
    S: CredentialStore + aegis_core::pin::PinState,
{
    let mut assembler = Assembler::new();
    let mut next_channel: u32 = 1;
    let mut session = FidoSession::new();
    let mut buf = [0u8; ctaphid::REPORT_SIZE];

    loop {
        let Ok(len) = reader.read(&mut buf).await else {
            continue;
        };
        if len != ctaphid::REPORT_SIZE {
            continue;
        }
        let Ok(packet) = ctaphid::parse_report(&buf) else {
            continue;
        };
        let channel = match &packet {
            ctaphid::Packet::Init { channel, .. } | ctaphid::Packet::Cont { channel, .. } => {
                *channel
            }
        };
        let is_init = matches!(
            &packet,
            ctaphid::Packet::Init {
                command: CtapHidCommand::Init,
                ..
            }
        );
        if !is_init && !ctaphid::allocated_channel(channel, next_channel) {
            let report = ctaphid::error_report(channel, CtapHidError::InvalidChannel);
            let _ = writer.write(&report).await;
            continue;
        }

        match assembler.accept(packet) {
            Ok(Some(message)) => {
                let mut chan = FidoChannel {
                    writer: &mut writer,
                    channel: message.channel,
                };
                handle_ctaphid(
                    &mut chan,
                    &mut next_channel,
                    &message,
                    store,
                    &mut session,
                    rng,
                    presence,
                )
                .await
            }
            Ok(None) => {}
            Err(_) => {
                let report = ctaphid::error_report(channel, CtapHidError::InvalidSeq);
                let _ = writer.write(&report).await;
            }
        }
    }
}

/// Handle one complete CTAPHID message.
async fn handle_ctaphid<S>(
    chan: &mut FidoChannel<'_>,
    next_channel: &mut u32,
    message: &ctaphid::Message,
    store: &mut S,
    session: &mut FidoSession,
    rng: &Mutex<CriticalSectionRawMutex, HardwareRng>,
    presence: &Mutex<CriticalSectionRawMutex, PresenceAdapter>,
) where
    S: CredentialStore + aegis_core::pin::PinState,
{
    match message.command {
        CtapHidCommand::Init => {
            match ctaphid::init_response(
                message.channel,
                &message.payload,
                next_channel,
                CTAPHID_CAPABILITIES,
            ) {
                Ok(response) => chan.send(CtapHidCommand::Init, &response).await,
                Err(error) => {
                    let report = ctaphid::error_report(message.channel, error);
                    chan.write(&report).await;
                }
            }
        }
        CtapHidCommand::Ping => {
            chan.send(CtapHidCommand::Ping, &message.payload).await;
        }
        CtapHidCommand::Cbor => {
            let mut out = [0u8; 512];
            let len = handle_ctap2(
                chan,
                &message.payload,
                &mut out,
                store,
                session,
                rng,
                presence,
            )
            .await;
            if let Some(&command) = message.payload.first() {
                LAST_CTAP_COMMAND.store(command, core::sync::atomic::Ordering::Relaxed);
            }
            if let Some(&status) = out.first() {
                LAST_CTAP_STATUS.store(status, core::sync::atomic::Ordering::Relaxed);
            }
            chan.send(CtapHidCommand::Cbor, &out[..len]).await;
        }
        CtapHidCommand::Msg => {
            let up = if u2f::requires_user_presence(&message.payload) {
                wait_presence_notifying(chan, ctaphid::KEEPALIVE_UP_NEEDED, presence).await
            } else {
                false
            };
            let response = u2f::handle(&message.payload, store, up);
            let mut out = [0u8; u2f::MAX_RESPONSE + 2];
            let len = response.encode_into(&mut out);
            chan.send(CtapHidCommand::Msg, &out[..len]).await;
        }
        CtapHidCommand::Wink => {
            chan.send(CtapHidCommand::Wink, &[]).await;
        }
        _ => {
            let report = ctaphid::error_report(message.channel, CtapHidError::InvalidCmd);
            chan.write(&report).await;
        }
    }
}

/// Write a single-byte CTAP2 status response.
fn write_status(status: ctap2::Ctap2Status, out: &mut [u8]) -> usize {
    out[0] = status.code();
    1
}

/// Encode a CTAP2 response, prefixed by the success status byte, or a status on
/// failure. CTAP2 responses are `status || CBOR` (status `0x00` = success).
fn encode_response<T: minicbor::Encode<()>>(value: &T, out: &mut [u8]) -> usize {
    if out.is_empty() {
        return 0;
    }
    match aegis_core::codec::encode_into(value, &mut out[1..]) {
        Ok(len) => {
            out[0] = 0x00;
            1 + len
        }
        Err(_) => write_status(ctap2::Ctap2Status::Other, out),
    }
}

/// Handle a CTAP2 request; returns the response payload length.
///
/// On success this is the CBOR-encoded response; on error it is the single
/// status byte, which is itself valid CBOR. User presence is required for
/// credential creation and assertion; the BOOTSEL context rule is enforced by
/// only asking for presence on these FIDO commands.
async fn handle_ctap2<S>(
    chan: &mut FidoChannel<'_>,
    payload: &[u8],
    out: &mut [u8],
    store: &mut S,
    session: &mut FidoSession,
    rng: &Mutex<CriticalSectionRawMutex, HardwareRng>,
    presence: &Mutex<CriticalSectionRawMutex, PresenceAdapter>,
) -> usize
where
    S: CredentialStore + aegis_core::pin::PinState,
{
    let Some((&command, params)) = payload.split_first() else {
        return write_status(ctap2::Ctap2Status::InvalidLength, out);
    };
    let client_pin = &mut session.client_pin;

    match ctap2::parse_request(command, params) {
        Ok(Ctap2Request::GetInfo) => {
            // Credential management is only offered when a PIN is set: the
            // platform must obtain a token with the `cm` permission.
            let info = ctap2::GetInfoResponse {
                options_cred_mgmt: aegis_core::pin::PinState::pin_hash(store).is_some(),
                ..ctap2::GetInfoResponse::default()
            };
            encode_response(&info, out)
        }
        Ok(Ctap2Request::MakeCredential(request)) => {
            let uv = match client_pin.authorize(
                store,
                TokenRequest {
                    param: request.pin_uv_auth_param.as_deref(),
                    message: &request.client_data_hash,
                    uv_requested: request.uv,
                    operation: TokenOperation::MakeCredential {
                        rp_id: request.rp_id.as_str(),
                    },
                },
            ) {
                Ok(uv) => uv,
                Err(status) => return write_status(status, out),
            };
            let up = wait_presence_notifying(chan, ctaphid::KEEPALIVE_PROCESSING, presence).await;
            let mut rng = rng.lock().await;
            let result = authenticator::make_credential(store, &mut *rng, &request, up, uv);
            // A token used in an operation that tests user presence loses
            // its permissions.
            client_pin.close_user_presence_operation(uv, result.is_ok());
            match result {
                Ok(response) => encode_response(&response, out),
                Err(status) => write_status(status, out),
            }
        }
        Ok(Ctap2Request::GetAssertion(request)) => {
            let uv = match client_pin.authorize(
                store,
                TokenRequest {
                    param: request.pin_uv_auth_param.as_deref(),
                    message: &request.client_data_hash,
                    uv_requested: request.uv,
                    operation: TokenOperation::GetAssertion {
                        rp_id: request.rp_id.as_str(),
                    },
                },
            ) {
                Ok(uv) => uv,
                Err(status) => return write_status(status, out),
            };
            let up = wait_presence_notifying(chan, ctaphid::KEEPALIVE_PROCESSING, presence).await;
            if !up {
                return write_status(ctap2::Ctap2Status::UpRequired, out);
            }
            let candidates = authenticator::assertion_candidates(store, &request);
            let Some(first) = candidates.first().cloned() else {
                return write_status(ctap2::Ctap2Status::NoCredentials, out);
            };
            let response = authenticator::sign_assertion(
                store,
                &first,
                request.rp_id.as_str(),
                &request.client_data_hash,
                uv,
            );
            // A token used in an operation that tests user presence loses
            // its permissions.
            client_pin.close_user_presence_operation(uv, response.is_ok());
            match response {
                Ok(response) => {
                    // The pending assertion is remembered only for a request
                    // that produced a signature, and only for the channel
                    // that asked for it.
                    session.assertion = Some(aegis_core::assertion::PendingAssertion::begin(
                        chan.channel,
                        candidates,
                        request.rp_id.clone(),
                        request.client_data_hash,
                        uv,
                    ));
                    encode_response(&response, out)
                }
                Err(status) => write_status(status, out),
            }
        }
        Ok(Ctap2Request::GetNextAssertion) => {
            // The presence was already confirmed by the first assertion.
            let Some(state) = session.assertion.as_mut() else {
                return write_status(ctap2::Ctap2Status::NoCredentials, out);
            };
            let Some(next) = state.next(chan.channel) else {
                return write_status(ctap2::Ctap2Status::NoCredentials, out);
            };
            match authenticator::sign_assertion(
                store,
                &next.credential_id,
                next.rp_id.as_str(),
                &next.client_data_hash,
                next.uv,
            ) {
                Ok(response) => encode_response(&response, out),
                Err(status) => write_status(status, out),
            }
        }
        Ok(Ctap2Request::ClientPin) => match ClientPinRequest::parse(params) {
            Ok(request) => match request.sub_command {
                SUB_GET_RETRIES => encode_response(&client_pin.get_retries(store), out),
                SUB_GET_KEY_AGREEMENT => {
                    let mut rng = rng.lock().await;
                    match client_pin.key_agreement(&mut *rng) {
                        Ok(response) => encode_response(&response, out),
                        Err(status) => write_status(status, out),
                    }
                }
                SUB_SET_PIN => match client_pin.set_pin(&request, store) {
                    Ok(()) => write_status(ctap2::Ctap2Status::Ok, out),
                    Err(status) => write_status(status, out),
                },
                SUB_CHANGE_PIN => match client_pin.change_pin(&request, store) {
                    Ok(()) => write_status(ctap2::Ctap2Status::Ok, out),
                    Err(status) => write_status(status, out),
                },
                SUB_GET_PIN_TOKEN | SUB_GET_PIN_UV_AUTH_TOKEN_WITH_PERMISSIONS => {
                    let mut rng = rng.lock().await;
                    match client_pin.get_pin_token(&request, store, &mut *rng) {
                        Ok(response) => encode_response(&response, out),
                        Err(status) => write_status(status, out),
                    }
                }
                _ => write_status(ctap2::Ctap2Status::InvalidSubcommand, out),
            },
            Err(status) => write_status(status, out),
        },
        Ok(Ctap2Request::Reset) => {
            let up = wait_presence_notifying(chan, ctaphid::KEEPALIVE_PROCESSING, presence).await;
            match authenticator::reset(store, client_pin, up) {
                Ok(()) => write_status(ctap2::Ctap2Status::Ok, out),
                Err(status) => write_status(status, out),
            }
        }
        Ok(Ctap2Request::CredentialManagement) => {
            match CredentialManagementRequest::parse(params) {
                Ok(request) => handle_credential_management(&request, store, session, out),
                Err(status) => write_status(status, out),
            }
        }
        Ok(_) => write_status(ctap2::Ctap2Status::InvalidCommand, out),
        Err(status) => write_status(status, out),
    }
}

/// Authorise a credential-management subcommand with the active token.
///
/// The decision — permission, relying-party scope and HMAC — belongs to
/// `aegis-core::pin`; the firmware only hands over the context of the
/// subcommand.
fn authorize_management<S>(
    client_pin: &mut ClientPin,
    store: &S,
    param: &[u8],
    message: &[u8],
    scope: ManagementScope<'_>,
) -> Result<(), ctap2::Ctap2Status>
where
    S: CredentialStore + aegis_core::pin::PinState,
{
    client_pin
        .authorize(
            store,
            TokenRequest {
                param: Some(param),
                message,
                uv_requested: false,
                operation: TokenOperation::CredentialManagement { scope },
            },
        )
        .map(|_| ())
}

/// Serve an `authenticatorCredentialManagement` request.
///
/// Every subcommand requires a PIN/UV auth token with the `cm` permission:
/// the platform authenticates the subcommand (and, when present, its
/// parameters) with the token.
fn handle_credential_management<S>(
    request: &CredentialManagementRequest,
    store: &mut S,
    session: &mut FidoSession,
    out: &mut [u8],
) -> usize
where
    S: CredentialStore + aegis_core::pin::PinState,
{
    let client_pin = &mut session.client_pin;
    match request.sub_command {
        authenticator::CRED_MGMT_GET_METADATA => {
            let Some(param) = request.pin_uv_auth_param.as_ref() else {
                return write_status(ctap2::Ctap2Status::PinRequired, out);
            };
            let message = [authenticator::CRED_MGMT_GET_METADATA];
            // The metadata of the device is global, so a token bound to a
            // single relying party cannot drive it.
            if let Err(status) = authorize_management(
                client_pin,
                store,
                param.as_slice(),
                &message,
                ManagementScope::Device,
            ) {
                return write_status(status, out);
            }
            encode_response(&authenticator::creds_metadata(store), out)
        }
        authenticator::CRED_MGMT_ENUMERATE_RPS => {
            let Some(param) = request.pin_uv_auth_param.as_ref() else {
                return write_status(ctap2::Ctap2Status::PinRequired, out);
            };
            let message = [authenticator::CRED_MGMT_ENUMERATE_RPS];
            // The enumeration of relying parties is global, so a token bound
            // to a single relying party cannot drive it.
            if let Err(status) = authorize_management(
                client_pin,
                store,
                param.as_slice(),
                &message,
                ManagementScope::Device,
            ) {
                return write_status(status, out);
            }
            let rps = authenticator::list_rps(store);
            if rps.is_empty() {
                return write_status(ctap2::Ctap2Status::NoCredentials, out);
            }
            let total_rps = rps.len() as u32;
            let first = rps[0].clone();
            session.enumeration.rps = rps;
            session.enumeration.rp_index = 1;
            encode_response(
                &authenticator::EnumerateRpsResponse {
                    rp: first,
                    total_rps,
                },
                out,
            )
        }
        authenticator::CRED_MGMT_ENUMERATE_RPS_NEXT => {
            let index = session.enumeration.rp_index;
            let Some(rp) = session.enumeration.rps.get(index).cloned() else {
                return write_status(ctap2::Ctap2Status::NoCredentials, out);
            };
            session.enumeration.rp_index = index + 1;
            let total_rps = session.enumeration.rps.len() as u32;
            encode_response(&authenticator::EnumerateRpsResponse { rp, total_rps }, out)
        }
        authenticator::CRED_MGMT_ENUMERATE_CREDENTIALS => {
            let Some(param) = request.pin_uv_auth_param.as_ref() else {
                return write_status(ctap2::Ctap2Status::PinRequired, out);
            };
            let Some(hash) = request.rp_id_hash else {
                return write_status(ctap2::Ctap2Status::MissingParameter, out);
            };
            let mut message = heapless::Vec::<u8, 128>::new();
            let _ = message.push(authenticator::CRED_MGMT_ENUMERATE_CREDENTIALS);
            let _ = message.extend_from_slice(&request.sub_command_params);
            // A token bound to a relying party only enumerates the
            // credentials of that relying party.
            if let Err(status) = authorize_management(
                client_pin,
                store,
                param.as_slice(),
                &message,
                ManagementScope::RelyingPartyHash(&hash),
            ) {
                return write_status(status, out);
            }
            let ids = authenticator::list_credentials(store, &hash);
            if ids.is_empty() {
                return write_status(ctap2::Ctap2Status::NoCredentials, out);
            }
            let total_credentials = ids.len() as u32;
            let first = ids[0].clone();
            session.enumeration.credentials = ids;
            session.enumeration.credential_index = 1;
            match credential_response(store, &first, total_credentials) {
                Some(response) => encode_response(&response, out),
                None => write_status(ctap2::Ctap2Status::NoCredentials, out),
            }
        }
        authenticator::CRED_MGMT_ENUMERATE_CREDENTIALS_NEXT => {
            let index = session.enumeration.credential_index;
            let Some(id) = session.enumeration.credentials.get(index).cloned() else {
                return write_status(ctap2::Ctap2Status::NoCredentials, out);
            };
            session.enumeration.credential_index = index + 1;
            let total_credentials = session.enumeration.credentials.len() as u32;
            match credential_response(store, &id, total_credentials) {
                Some(response) => encode_response(&response, out),
                None => write_status(ctap2::Ctap2Status::NoCredentials, out),
            }
        }
        authenticator::CRED_MGMT_DELETE => {
            let Some(param) = request.pin_uv_auth_param.as_ref() else {
                return write_status(ctap2::Ctap2Status::PinRequired, out);
            };
            let Some(id) = request.credential_id.as_ref() else {
                return write_status(ctap2::Ctap2Status::MissingParameter, out);
            };
            let mut message = heapless::Vec::<u8, 128>::new();
            let _ = message.push(authenticator::CRED_MGMT_DELETE);
            let _ = message.extend_from_slice(&request.sub_command_params);
            // The credential must belong to the relying party the token is
            // bound to; the other credentials are preserved.
            match authenticator::delete_credential_scoped(
                store,
                client_pin,
                Some(param.as_slice()),
                &message,
                id,
            ) {
                Ok(()) => write_status(ctap2::Ctap2Status::Ok, out),
                Err(status) => write_status(status, out),
            }
        }
        _ => write_status(ctap2::Ctap2Status::InvalidSubcommand, out),
    }
}

/// Build the `enumerateCredentials` response for one credential.
fn credential_response<S>(
    store: &S,
    credential_id: &[u8],
    total_credentials: u32,
) -> Option<authenticator::EnumerateCredentialsResponse>
where
    S: CredentialStore + aegis_core::pin::PinState,
{
    let credential = store.get(credential_id)?;
    let public_key = authenticator::cose_public_key(&credential)?;
    Some(authenticator::EnumerateCredentialsResponse {
        user_id: credential.user_id.clone(),
        credential_id: credential.id.clone(),
        public_key,
        total_credentials,
    })
}

/// Split a CTAPHID payload across initialization and continuation reports.
async fn send_ctaphid(
    writer: &mut FidoWriter,
    channel: u32,
    command: CtapHidCommand,
    payload: &[u8],
) {
    let first = payload.len().min(ctaphid::INIT_DATA_LEN);
    let Ok(report) =
        ctaphid::init_report(channel, command, payload.len() as u16, &payload[..first])
    else {
        return;
    };
    if writer.write(&report).await.is_err() {
        return;
    }

    let mut offset = first;
    let mut sequence = 0u8;
    while offset < payload.len() {
        let end = (offset + ctaphid::CONT_DATA_LEN).min(payload.len());
        let Ok(report) = ctaphid::cont_report(channel, sequence, &payload[offset..end]) else {
            return;
        };
        if writer.write(&report).await.is_err() {
            return;
        }
        offset = end;
        sequence = sequence.saturating_add(1) & 0x7F;
    }
}

/// Serve the Management HID protocol and keep the LED and watchdog alive.
async fn housekeeping<const FLASH_SIZE: usize>(
    mut reader: ManagementReader,
    mut writer: ManagementWriter,
    service: &mut ManagementService,
    storage: &CriticalSectionMutex<RefCell<FlashStorage<FLASH_SIZE>>>,
    mut led: Option<&mut dyn Led>,
    watchdog: &mut WatchdogHandle,
) {
    let mut assembler = aegis_core::management::Assembler::new();
    let mut buf = [0u8; aegis_core::management::REPORT_SIZE];
    let mut update_handler = UpdateHandler::default();
    let mut led_on = false;

    loop {
        match select(reader.read(&mut buf), Timer::after_millis(500)).await {
            Either::First(Ok(_len)) => {
                let Ok(frame) = aegis_core::management::parse_report(&buf) else {
                    continue;
                };
                let Ok(Some(message)) = assembler.accept(frame) else {
                    continue;
                };

                // Transport body: one status byte followed by the payload.
                let mut body = [0u8; 513];
                let mut soft_detach = false;
                // Flash is shared with the CCID task; each storage call locks
                // briefly and regions never overlap between writers.
                let (response_code, body_len) = storage.lock(|cell| {
                    let storage = &mut *cell.borrow_mut();
                    let (response_code, body_len) =
                        if (update::CMD_BEGIN..=update::CMD_ABORT).contains(&message.command) {
                            let length = handle_update(
                                message.command,
                                &message.payload,
                                &mut update_handler,
                                storage,
                                &mut body,
                            );
                            (message.command | 0x80, length)
                        } else if message.command == CMD_GET_LAST_FIDO_STATUS {
                            body[0] = 0x00;
                            body[1] = LAST_CTAP_COMMAND.load(core::sync::atomic::Ordering::Relaxed);
                            body[2] = LAST_CTAP_STATUS.load(core::sync::atomic::Ordering::Relaxed);
                            (CMD_GET_LAST_FIDO_STATUS | 0x80, 3)
                        } else {
                            let command = ManagementCommand::from_code(message.command);
                            let response = service.handle(command, &message.payload);
                            body[0] = response.status.code();
                            let length = 1 + response.payload.len();
                            body[1..length].copy_from_slice(&response.payload);
                            if response.status.is_ok() {
                                match command {
                                    // Live preview: apply the staged configuration to the
                                    // LED as soon as it is accepted.
                                    ManagementCommand::SetConfiguration => {
                                        if let Some(staged) = service.staged() {
                                            apply_led_config(&mut led, staged);
                                        }
                                    }
                                    // Persist and apply the now-active configuration.
                                    ManagementCommand::CommitConfiguration => {
                                        let identity = service.identity();
                                        persist_config(&mut *storage, service.config());
                                        apply_led_config(&mut led, service.config());
                                        if service.config().usb.vid != identity.vendor_id
                                            || service.config().usb.pid != identity.product_id
                                            || service.config().usb.product_string.as_str()
                                                != identity.product
                                        {
                                            info!("USB identity updated; scheduling soft detach for re-enumeration");
                                            soft_detach = true;
                                        }
                                    }
                                    _ => {}
                                }
                            }
                            soft_detach = soft_detach
                                || (command == ManagementCommand::SoftDetach
                                    && response.status.is_ok());
                            (command.response_code(), length)
                        };
                    (response_code, body_len)
                });
                send_management(&mut writer, response_code, &body[..body_len]).await;

                // Signal only after the acknowledgement has been transmitted, so
                // the host sees the reply before the device detaches.
                if soft_detach {
                    DETACH.signal(());
                }
            }
            Either::First(Err(_)) => {}
            Either::Second(()) => {
                led_on = !led_on;
                if let Some(led) = led.as_mut() {
                    let config = service.config();
                    let behavior = if !config.led.enabled {
                        LedBehavior::Off
                    } else {
                        match config.led.behavior {
                            LedBehavior::Off => LedBehavior::Off,
                            LedBehavior::Solid => LedBehavior::Solid,
                            LedBehavior::Activity | LedBehavior::Blink => {
                                if led_on {
                                    LedBehavior::Solid
                                } else {
                                    LedBehavior::Off
                                }
                            }
                        }
                    };
                    let _ = led.set_behavior(behavior);
                }
                watchdog.feed(WATCHDOG_TIMEOUT);
            }
        }
    }
}

/// In-flight firmware update session.
#[derive(Default)]
struct UpdateHandler {
    session: Option<UpdateSession>,
}

fn update_ok(out: &mut [u8]) -> usize {
    out[0] = 0;
    1
}

fn update_error(out: &mut [u8]) -> usize {
    out[0] = aegis_core::CoreError::FirmwareError.code();
    1
}

/// Handle a firmware-update management command.
fn handle_update(
    command: u8,
    payload: &[u8],
    handler: &mut UpdateHandler,
    storage: &mut dyn Storage,
    out: &mut [u8],
) -> usize {
    match command {
        update::CMD_BEGIN => {
            match UpdateSession::begin(
                payload,
                &VENDOR_PUBLIC_KEY,
                INSTALLED_ROLLBACK,
                STAGING_BASE,
                STAGING_ERASE_SIZE,
                storage,
            ) {
                Ok(session) => {
                    handler.session = Some(session);
                    update_ok(out)
                }
                Err(_) => update_error(out),
            }
        }
        update::CMD_WRITE => {
            let Some(session) = handler.session.as_mut() else {
                return update_error(out);
            };
            match session.write(storage, payload) {
                Ok(()) => update_ok(out),
                Err(_) => update_error(out),
            }
        }
        update::CMD_FINISH => {
            let Some(session) = handler.session.take() else {
                return update_error(out);
            };
            match session.finish(storage) {
                Ok(image) => {
                    info!(
                        "firmware update verified: {}.{}.{}",
                        image.version.major, image.version.minor, image.version.patch
                    );
                    update_ok(out)
                }
                Err(_) => update_error(out),
            }
        }
        update::CMD_ABORT => {
            handler.session = None;
            update_ok(out)
        }
        _ => update_error(out),
    }
}

/// Split a Management HID payload across initialization and continuation reports.
async fn send_management(writer: &mut ManagementWriter, command: u8, payload: &[u8]) {
    use aegis_core::management::PAYLOAD_PER_REPORT;

    let first = payload.len().min(PAYLOAD_PER_REPORT);
    let Ok(report) =
        aegis_core::management::init_report(command, payload.len() as u16, &payload[..first])
    else {
        return;
    };
    if writer.write(&report).await.is_err() {
        return;
    }

    let mut offset = first;
    let mut sequence = 0u16;
    while offset < payload.len() {
        let end = (offset + PAYLOAD_PER_REPORT).min(payload.len());
        let Ok(report) =
            aegis_core::management::cont_report(command, sequence, &payload[offset..end])
        else {
            return;
        };
        if writer.write(&report).await.is_err() {
            return;
        }
        offset = end;
        sequence += 1;
    }
}
